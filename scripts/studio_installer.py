"""Generate the Command Bar installer from the scripts mounted by Rojo."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / "InstallInStudio.lua"
MOUNTS = (
    (("ReplicatedStorage", "MiningConfig"), "ModuleScript"),
    (("ReplicatedStorage", "MiningAudio"), "ModuleScript"),
    (("ReplicatedStorage", "BiomeView"), "ModuleScript"),
    (("ServerScriptService", "Pickaxes"), "ModuleScript"),
    (("ServerScriptService", "World"), "ModuleScript"),
    (("ServerScriptService", "Premium"), "ModuleScript"),
    (("ServerScriptService", "SessionStore"), "ModuleScript"),
    (("ServerScriptService", "MiningServer"), "Script"),
    (("StarterPlayer", "StarterPlayerScripts", "MiningClient"), "LocalScript"),
)

HEADER = """-- Generated by scripts/studio_installer.py. Run in the Studio Command Bar in Edit mode.
local function install(parent, name, className, source)
    local old = parent:FindFirstChild(name)
    if old then old:Destroy() end
    local object = Instance.new(className)
    object.Name = name
    object.Source = source
    object.Parent = parent
    return object
end
"""


def render():
    tree = json.loads((ROOT / "default.project.json").read_text())["tree"]
    chunks = [HEADER]
    for path, kind in MOUNTS:
        node = tree
        for segment in path:
            node = node[segment]
        source = (ROOT / node["$path"]).read_text()
        delimiter = "="
        while f"]{delimiter}]" in source:
            delimiter += "="
        parent = f'game:GetService("{path[0]}")'
        for child in path[1:-1]:
            parent += f':WaitForChild("{child}")'
        prefix = "local worldModule = " if path[-1] == "World" else ""
        chunks.append(
            f'{prefix}install({parent}, "{path[-1]}", "{kind}", '
            f'[{delimiter}[\n{source}]{delimiter}])\n'
        )
        if prefix:
            chunks.append("require(worldModule).ensureSpawn()\n")
    chunks.append('print("Crystal Mining Simulator installed. Press Play to test.")\n')
    return "".join(chunks)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    updated = render()
    if args.check:
        if INSTALLER.read_text() != updated:
            raise SystemExit("Studio installer is stale. Run python3 scripts/studio_installer.py")
    else:
        INSTALLER.write_text(updated)


if __name__ == "__main__":
    main()
